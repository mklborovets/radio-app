import React, { useEffect, useRef, useState } from 'react';
import {
  Animated,
  PanResponder,
  StyleSheet,
  Text,
  TouchableOpacity,
  View,
} from 'react-native';
import { PlayableTrack } from '@entities/player';
import { COLORS } from '@shared/ui';
import { QUEUE_ROW_HEIGHT, useQueueSheet } from './model';

const ROW_GAP = 8;
const ROW_TOTAL_HEIGHT = QUEUE_ROW_HEIGHT + ROW_GAP;

export interface QueueSheetProps {
  onDragStart?: () => void;
  onDragEnd?: () => void;
}

interface QueueRowItemProps {
  item: PlayableTrack;
  index: number;
  totalCount: number;
  isActive: boolean;
  isDragging: boolean;
  anyDragging: boolean;
  dragY: Animated.Value;
  hoverIndex: number | null;
  draggingIndex: number | null;
  onStartDrag: (index: number) => void;
  onMoveDrag: (dy: number) => void;
  onEndDrag: () => void;
  onSelectTrack: (track: PlayableTrack) => void;
  onRemoveTrack: (trackId: string) => void;
}

function QueueRowItem({
  item,
  index,
  isActive,
  isDragging,
  anyDragging,
  dragY,
  hoverIndex,
  draggingIndex,
  onStartDrag,
  onMoveDrag,
  onEndDrag,
  onSelectTrack,
  onRemoveTrack,
}: QueueRowItemProps): React.JSX.Element {
  const offsetY = useRef(new Animated.Value(0)).current;

  const indexRef = useRef(index);
  indexRef.current = index;

  const isDraggingRef = useRef(isDragging);
  isDraggingRef.current = isDragging;

  const anyDraggingRef = useRef(anyDragging);
  anyDraggingRef.current = anyDragging;

  const onStartDragRef = useRef(onStartDrag);
  onStartDragRef.current = onStartDrag;

  const onMoveDragRef = useRef(onMoveDrag);
  onMoveDragRef.current = onMoveDrag;

  const onEndDragRef = useRef(onEndDrag);
  onEndDragRef.current = onEndDrag;

  useEffect(() => {
    if (draggingIndex === null) {
      offsetY.setValue(0);
      return;
    }

    if (isDragging) {
      offsetY.setValue(0);
      return;
    }

    let targetOffset = 0;
    if (hoverIndex !== null) {
      if (draggingIndex < hoverIndex && index > draggingIndex && index <= hoverIndex) {
        targetOffset = -ROW_TOTAL_HEIGHT;
      } else if (draggingIndex > hoverIndex && index < draggingIndex && index >= hoverIndex) {
        targetOffset = ROW_TOTAL_HEIGHT;
      }
    }

    Animated.spring(offsetY, {
      toValue: targetOffset,
      useNativeDriver: false,
      friction: 8,
      tension: 100,
    }).start();
  }, [draggingIndex, hoverIndex, index, isDragging, offsetY]);

  const panResponder = useRef(
    PanResponder.create({
      onStartShouldSetPanResponder: () => !anyDraggingRef.current,
      onStartShouldSetPanResponderCapture: () => !anyDraggingRef.current,
      onMoveShouldSetPanResponder: () => isDraggingRef.current,
      onMoveShouldSetPanResponderCapture: () => isDraggingRef.current,
      onPanResponderTerminationRequest: () => false,
      onPanResponderGrant: () => {
        onStartDragRef.current(indexRef.current);
      },
      onPanResponderMove: (_evt, gestureState) => {
        onMoveDragRef.current(gestureState.dy);
      },
      onPanResponderRelease: () => {
        onEndDragRef.current();
      },
      onPanResponderTerminate: () => {
        onEndDragRef.current();
      },
    }),
  ).current;

  const sourceLabel =
    item.sourceType === 'radio'
      ? 'RADIO'
      : item.isAutoGenerated
      ? 'UP NEXT'
      : 'QUEUED';

  const currentTranslateY = isDragging ? dragY : offsetY;

  return (
    <Animated.View
      pointerEvents={anyDragging && !isDragging ? 'none' : 'auto'}
      style={[
        styles.row,
        isActive && styles.rowActive,
        isDragging ? styles.rowDragging : styles.rowDefault,
        {
          transform: [
            { translateY: currentTranslateY },
            { scale: isDragging ? 1.03 : 1 },
          ],
        },
      ]}>
      <View
        style={styles.dragHandle}
        hitSlop={{ left: 8, right: 8 }}
        {...(isDragging || !anyDragging ? panResponder.panHandlers : {})}>
        <Text style={[styles.dragHandleIcon, isDragging && styles.dragHandleIconDragging]}>
          :::
        </Text>
      </View>

      <TouchableOpacity
        style={styles.trackInfo}
        onPress={() => onSelectTrack(item)}
        activeOpacity={0.8}
        disabled={anyDragging}>
        <Text style={styles.trackTitle} numberOfLines={1}>
          {index + 1}. {item.title}
        </Text>
        <Text style={styles.trackSubtitle} numberOfLines={1}>
          {sourceLabel} • {item.subtitle}
        </Text>
      </TouchableOpacity>

      <TouchableOpacity
        style={styles.removeBtn}
        onPress={() => onRemoveTrack(item.id)}
        hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}
        disabled={anyDragging}>
        <Text style={styles.removeBtnText}>✕</Text>
      </TouchableOpacity>
    </Animated.View>
  );
}

export function QueueSheet({
  onDragStart,
  onDragEnd,
}: QueueSheetProps = {}): React.JSX.Element {
  const {
    queue,
    activeTrackId,
    onSelectTrack,
    onMoveTrack,
    onRemoveTrack,
    onClearQueue,
  } = useQueueSheet();

  const [draggingIndex, setDraggingIndex] = useState<number | null>(null);
  const [hoverIndex, setHoverIndex] = useState<number | null>(null);

  const dragY = useRef(new Animated.Value(0)).current;
  const startIndexRef = useRef<number | null>(null);
  const hoverIndexRef = useRef<number | null>(null);
  const queueLengthRef = useRef(queue.length);
  queueLengthRef.current = queue.length;

  const handleStartDrag = (index: number) => {
    startIndexRef.current = index;
    hoverIndexRef.current = index;
    dragY.setValue(0);
    setDraggingIndex(index);
    setHoverIndex(index);
    onDragStart?.();
  };

  const handleMoveDrag = (dy: number) => {
    dragY.setValue(dy);
    const start = startIndexRef.current;
    if (start === null) {
      return;
    }

    const shift = Math.round(dy / ROW_TOTAL_HEIGHT);
    const target = Math.max(0, Math.min(queueLengthRef.current - 1, start + shift));

    if (target !== hoverIndexRef.current) {
      hoverIndexRef.current = target;
      setHoverIndex(target);
    }
  };

  const handleEndDrag = () => {
    const from = startIndexRef.current;
    const to = hoverIndexRef.current;

    startIndexRef.current = null;
    hoverIndexRef.current = null;
    dragY.setValue(0);
    setDraggingIndex(null);
    setHoverIndex(null);
    onDragEnd?.();

    if (from !== null && to !== null && from !== to) {
      onMoveTrack(from, to);
    }
  };

  const anyDragging = draggingIndex !== null;

  return (
    <View style={styles.container}>
      <View style={styles.headerRow}>
        <View style={styles.headerTitleBox}>
          <Text style={styles.title}>Up Next Queue ({queue.length})</Text>
          <Text style={styles.hint}>Drag ::: to reorder</Text>
        </View>
        {queue.length > 0 && (
          <TouchableOpacity
            style={styles.clearBtn}
            onPress={onClearQueue}
            hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}>
            <Text style={styles.clearBtnText}>CLEAR ALL</Text>
          </TouchableOpacity>
        )}
      </View>

      {queue.length === 0 ? (
        <Text style={styles.emptyText}>
          Queue is empty. Tap &quot;+ QUEUE&quot; on any radio station or podcast episode to build your playlist.
        </Text>
      ) : (
        queue.map((item, idx) => (
          <QueueRowItem
            key={item.id}
            item={item}
            index={idx}
            totalCount={queue.length}
            isActive={activeTrackId === item.id}
            isDragging={draggingIndex === idx}
            anyDragging={anyDragging}
            dragY={dragY}
            hoverIndex={hoverIndex}
            draggingIndex={draggingIndex}
            onStartDrag={handleStartDrag}
            onMoveDrag={handleMoveDrag}
            onEndDrag={handleEndDrag}
            onSelectTrack={onSelectTrack}
            onRemoveTrack={onRemoveTrack}
          />
        ))
      )}
    </View>
  );
}

